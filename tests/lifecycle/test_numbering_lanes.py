def build(mode="auto", stab="compact", gap=1, starts=None, range_start=101, range_end=None,
          locked=None):
    c = sqlite3.connect(":memory:")
    c.row_factory = sqlite3.Row
    c.executescript(SCHEMA)
    c.execute(
        "UPDATE settings SET global_channel_mode=?, channel_stability_mode=?, channel_gap_size=?, "
        "league_channel_starts=?, channel_range_start=?, channel_range_end=?",
        (mode, stab, gap, json.dumps(starts or {}), range_start, range_end),
    )
    for s, lg, p in PRIORITIES:
        c.execute(
            "INSERT INTO channel_sort_priorities (sport, league_code, sort_priority)"
            " VALUES (?,?,?)",
            (s, lg, p),
        )
    locked = locked or {}
    for row in CHANNELS:
        cid, name, num, lk, date, eid, sport, league, home, away, kw = row
        if cid in locked:
            num, lk = locked[cid], 1
        c.execute(
            "INSERT INTO managed_channels (id, channel_name, channel_number, channel_number_locked,"
            " event_date, event_id, sport, league, home_team, away_team, exception_keyword)"
            " VALUES (?,?,?,?,?,?,?,?,?,?,?)",
            (cid, name, num, lk, date, eid, sport, league, home, away, kw),
        )
    return c


def numbers(c) -> dict[int, int]:
    return {
        r["id"]: int(r["channel_number"])
        for r in c.execute("SELECT id, channel_number FROM managed_channels ORDER BY id")
        if r["channel_number"] is not None
    }


def pin(c, scope, start, **kw):
    exc = ne.add_numbering_exception(c, scope=scope, start=start, **kw)
    assert exc is not None, f"pin failed: {scope} {start} {kw}"
    return exc


