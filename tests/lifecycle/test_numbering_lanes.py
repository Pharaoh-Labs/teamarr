# Pre-#333 `_reassign_manual` output for starts {nfl:500, nba:600, nhl:700}, range 101:
# listed leagues sequential from their start; EVERY unlisted league restarted at
# 101 independently (ids 8, 10, 11 all = 101 — a collision). Lanes keep the listed
# numbers exactly and fix the collision.
MANUAL_LISTED = {1: 500, 2: 501, 3: 502, 4: 503, 5: 600, 6: 601, 7: 700}


def _migrate(c):
    from teamarr.database.migrations.versioned import _migrate_v88_numbering_exceptions

    _migrate_v88_numbering_exceptions(c)


def test_v88_manual_listed_leagues_identical_and_unlisted_fixed():
    c = build(mode="manual", starts={"nfl": 500, "nba": 600, "nhl": 700}, range_start=101)
    _migrate(c)
    settings = c.execute(
        "SELECT global_channel_mode, channel_stability_mode FROM settings"
    ).fetchone()
    assert settings["global_channel_mode"] == "auto"
    assert settings["channel_stability_mode"] == "compact"
    rows = ne.get_numbering_exceptions(c)
    assert [(r.scope, r.league_code, r.start, r.sport) for r in rows] == [
        ("league", "nfl", 500, "football"),
        ("league", "nba", 600, "basketball"),
        ("league", "nhl", 700, "hockey"),
    ]

    cn.reassign_all_channels(c)
    got = numbers(c)
    assert {k: got[k] for k in MANUAL_LISTED} == MANUAL_LISTED
    # Unlisted leagues share the default lane in sort order (ncaaf before mlb x2, wc last).
    assert (got[10], got[8], got[9], got[11]) == (101, 102, 103, 104)


def test_v88_manual_with_external_occupied_matches_listed():
    # Pre-#333: {1:501, 2:502, 3:503, 4:504, 5:600, 6:602} with ext {500, 601}
    c = build(mode="manual", starts={"nfl": 500, "nba": 600}, range_start=101)
    _migrate(c)
    cn.reassign_all_channels(c, external_occupied={500, 601})
    got = numbers(c)
    expected = {1: 501, 2: 502, 3: 503, 4: 504, 5: 600, 6: 602}
    assert {k: got[k] for k in expected} == expected


def test_v88_next_channel_for_pinned_league_matches_manual():
    # Pre-#333: next for nfl after reassign = 504; unlisted league = 103
    c = build(mode="manual", starts={"nfl": 500})
    _migrate(c)
    cn.reassign_all_channels(c)
    assert cn.get_next_channel_number(c, league="nfl", sport="football") == 504
    # unlisted leagues now share the default lane: 7 channels there → 101..107, next 108
    assert cn.get_next_channel_number(c, league="mlb", sport="baseball") == 108


def test_v88_auto_mode_untouched():
    c = build(mode="auto", stab="gap", gap=3, starts={"nfl": 500})
    _migrate(c)
    settings = c.execute("SELECT channel_stability_mode FROM settings").fetchone()
    assert settings["channel_stability_mode"] == "gap"
    assert ne.get_numbering_exceptions(c) == []


def test_v88_is_idempotent():
    c = build(mode="manual", starts={"nfl": 500})
    _migrate(c)
    c.execute("UPDATE settings SET global_channel_mode = 'manual'")
    _migrate(c)
    assert len(ne.get_numbering_exceptions(c)) == 1


