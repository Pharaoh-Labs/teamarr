def test_team_pin_covers_both_sides_and_feeds():
    c = build()
    pin(c, "team", 800, provider="espn", provider_team_id="8")  # Lions (away in nfl1)
    cn.reassign_all_channels(c)
    got = numbers(c)
    assert (got[1], got[2]) == (800, 801)  # both feeds of the Lions game, contiguous
    # everything else compact from 101 in sort order, Lions game removed
    assert got[3] == 101 and got[10] == 103 and got[5] == 104


def test_detroit_example_layout():
    """The motivating layout from #333: four team pins + a big-events group + default."""
    c = build(range_start=8000)
    pin(c, "team", 800, provider="espn", provider_team_id="8")   # Lions
    pin(c, "team", 810, provider="espn", provider_team_id="20")  # Pistons
    pin(c, "team", 820, provider="espn", provider_team_id="17")  # Red Wings
    pin(c, "team", 830, provider="espn", provider_team_id="6")   # Tigers
    pin(c, "league", 850, league_code="fifa.world", label="Big events")
    pin(c, "league", 1700, league_code="nfl")
    cn.reassign_all_channels(c)
    got = numbers(c)
    assert (got[1], got[2]) == (800, 801)
    assert got[5] == 810
    assert got[7] == 820
    assert (got[8], got[9]) == (830, 831)
    assert got[11] == 850
    assert (got[3], got[4]) == (1700, 1701)  # NFL game without a pinned team
    assert (got[10], got[6]) == (8000, 8001)  # ncaaf, then nba (sort order)


def test_precedence_home_team_beats_away_team():
    c = build()
