def test_group_rows_share_one_lane():
    c = build()
    pin(c, "league", 850, league_code="fifa.world", label="Big events")
    pin(c, "league", 850, league_code="nhl", label="Big events")
    cn.reassign_all_channels(c)
    got = numbers(c)
    # nhl sorts before soccer (priority 2 vs unset) → 850, then World Cup 851
    assert (got[7], got[11]) == (850, 851)
    resolver = ne.LaneResolver.load(c, cn._default_lane(c))
    assert len(resolver.lanes()) == 2  # one grouped lane + default


def test_spill_forward_into_next_block():
    c = build(range_start=5000)
    pin(c, "league", 100, league_code="nfl")   # 4 channels: 100-103
    pin(c, "league", 102, league_code="nba")   # would start inside NFL's spill
    cn.reassign_all_channels(c)
    got = numbers(c)
    assert [got[i] for i in (1, 2, 3, 4)] == [100, 101, 102, 103]
    assert (got[5], got[6]) == (104, 105)      # skipped over the spill, no collision


def test_bounded_block_overflows_to_default():
    c = build(range_start=5000)
    pin(c, "league", 100, league_code="nfl", end=101)  # room for 2 of 4
    cn.reassign_all_channels(c)
    got = numbers(c)
    assert (got[1], got[2]) == (100, 101)
    # overflow lands at the tail of the default lane
    default_numbers = sorted(v for k, v in got.items() if k not in (1, 2))
    assert default_numbers[0] == 5000
    assert got[3] > 5000 and got[4] == got[3] + 1


def test_bounded_block_next_channel_overflows_to_default():
    c = build(range_start=5000)
    pin(c, "league", 100, league_code="nfl", end=101)
    c.execute("UPDATE managed_channels SET channel_number = 100 WHERE id = 1")
    c.execute("UPDATE managed_channels SET channel_number = 101 WHERE id = 2")
    assert cn.get_next_channel_number(c, league="nfl", sport="football") == 5000


