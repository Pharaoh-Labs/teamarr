"""Numbering lanes — pinned blocks (#333) and the golden-equivalence guarantee.

Two families of tests:

1. **Golden equivalence.** With zero pinned blocks, ``reassign_all_channels`` and
   ``get_next_channel_number`` must produce *exactly* the numbers the pre-#333
   allocator produced. The expected maps below were generated by running the
   pre-#333 code (``teamarr/database/channel_numbers.py`` at dev ``0129cda1``)
   against the same fixture — do not "fix" them to match new output.

2. **Lane behaviour.** Team / league / sport pins, precedence, groups, spill,
   bounded overflow, stability modes inside lanes, relayout arming, and the v88
   migration from manual mode.
"""

